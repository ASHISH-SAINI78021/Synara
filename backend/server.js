// server.js
import "dotenv/config";
import express from "express";
import cors from "cors";
import { connectDB } from "./config/db.js";
import api from "./routes/api.js";
import bookings from "./routes/bookings.js";
import uploads from "./routes/uploads.js";
import admin from "./routes/admin.js";
import auth from "./routes/auth.js";
import orders from "./routes/orders.js";
import riders from "./routes/riders.js";
import riderUploads from "./routes/riderUploads.js";
const app = express();
const origins = (process.env.CORS_ORIGINS || "http://localhost:5173").split(",").map((o) => o.trim()).filter(Boolean);
app.use(cors({ origin: origins }));
app.use(express.json({ limit: "1mb" }));
app.use("/api/uploads", uploads);
app.use("/api/rider-uploads", riderUploads);
app.get("/", (_req, res) => res.json({ ok: true, name: "Synara API" }));
app.get("/api/health", (_req, res) => res.json({ ok: true }));
app.use("/api/admin", admin);
app.use("/api/auth", auth);
app.use("/api/orders", orders);
app.use("/api/riders", riders);
app.use("/api/bookings", bookings);
app.use("/api", api);
app.use((req, res) => res.status(404).json({ error: "Not found" }));
app.use((err, _req, res, _next) => { console.error(err); res.status(500).json({ error: "Server error" }); });
const PORT = process.env.PORT || 5000;
connectDB().then(() => app.listen(PORT, () => console.log(`Synara API running on http://localhost:${PORT}`)));
